x = 10
y = 20
z = 30

# Using 'and' operater
if x < y and y < z:
    print("x is less than y and y is less than z. " ) # True

# Using ' or' operater
if x < y or y > z:
    print("x is less than y or y is greater than z. " ) # True
    
# Using the 'not' operater
if not(x > y ):
    print("x is not greater than y. " ) # True